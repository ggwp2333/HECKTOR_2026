import numpy as np
import nibabel as nib
import matplotlib.pyplot as plt
from nibabel.processing import resample_from_to
from matplotlib.colors import ListedColormap

# Select patient
patient_dir = patient_dirs[0]  # Change patient index here
patient_id = os.path.basename(patient_dir)

ct = nib.load(os.path.join(patient_dir, f"{patient_id}__CT.nii.gz"))
pet = nib.load(os.path.join(patient_dir, f"{patient_id}__PT.nii.gz"))
gt = nib.as_closest_canonical(
    nib.load(os.path.join(patient_dir, f"{patient_id}.nii.gz"))
)

# Find the axial slice containing the most labeled tumor voxels
labels = np.asarray(gt.dataobj)
tumor_area = (labels > 0).sum(axis=(0, 1))  # Use labels == 1 for primary tumor only

if tumor_area.max() == 0:
    raise ValueError("No tumor labels found for this patient.")

z = int(tumor_area.argmax())
gt_slice = gt.slicer[:, :, z:z + 1]

# Sample CT and PET onto the selected GT slice's physical grid
ct_slice = resample_from_to(ct, gt_slice, order=1).get_fdata()[:, :, 0]
pet_slice = resample_from_to(pet, gt_slice, order=1).get_fdata()[:, :, 0]

fig, axes = plt.subplots(1, 3, figsize=(15, 5))
axes[0].imshow(ct_slice.T, cmap="gray", origin="lower", vmin=-160, vmax=240)
axes[1].imshow(pet_slice.T, cmap="hot", origin="lower", vmin=0)
mask = axes[2].imshow(
    labels[:, :, z].T, origin="lower",
    cmap=ListedColormap(["black", "lime", "cyan"]),
    vmin=-0.5, vmax=2.5
)

for ax, title in zip(axes, ["CT", "PET", "Ground truth"]):
    ax.set_title(title)
    ax.set_aspect(gt.header.get_zooms()[1] / gt.header.get_zooms()[0])
    ax.axis("off")

cbar = fig.colorbar(mask, ax=axes[2], ticks=[0, 1, 2], fraction=0.046)
cbar.ax.set_yticklabels(["Background", "Primary tumor", "Secondary tumor"])

fig.suptitle(f"{patient_id} — Tumor slice {z}")
plt.tight_layout()
plt.show()

