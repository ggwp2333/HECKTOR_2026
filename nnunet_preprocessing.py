for patient_dir in patient_dirs:
    patient_id = os.path.basename(patient_dir)

    gt_path = os.path.join(patient_dir, f"{patient_id}.nii.gz")
    ct_path = os.path.join(patient_dir, f"{patient_id}__CT.nii.gz")
    pet_path = os.path.join(patient_dir, f"{patient_id}__PT.nii.gz")

    assert os.path.exists(gt_path), f"Missing GT: {gt_path}"
    assert os.path.exists(ct_path), f"Missing CT: {ct_path}"
    assert os.path.exists(pet_path), f"Missing PET: {pet_path}"

    # nnU-Net channel convention
    # _0000 = CT
    # _0001 = PET
    shutil.copy2(
        ct_path,
        os.path.join(imagesTr, f"{patient_id}_0000.nii.gz")
    )

    shutil.copy2(
        pet_path,
        os.path.join(imagesTr, f"{patient_id}_0001.nii.gz")
    )

    shutil.copy2(
        gt_path,
        os.path.join(labelsTr, f"{patient_id}.nii.gz")
    )

